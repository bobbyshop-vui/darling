/*
 * The AVAudio* classes are really declared by AVFAudio.framework, but many
 * clients link them through AVFoundation. These stubs only exist so that
 * dyld can resolve the _OBJC_CLASS_$_... non-lazy bind targets.
 */

@interface AVAudioEngine : NSObject
@end

@implementation AVAudioEngine

- (NSMethodSignature *) methodSignatureForSelector: (SEL) aSelector {
    return [NSMethodSignature signatureWithObjCTypes: "v@:"];
}

- (void) forwardInvocation: (NSInvocation *) anInvocation {
    NSLog(@"Stub called: %@ in %@",
          NSStringFromSelector([anInvocation selector]), [self class]);
}

@end

